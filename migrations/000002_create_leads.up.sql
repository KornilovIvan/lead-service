CREATE TABLE leads (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES customers (id),
    name text NOT NULL,
    phone text NULL,
    email text NULL,
    status text NOT NULL DEFAULT 'new',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT leads_status_check CHECK (status IN ('new', 'qualified', 'rejected'))
);

CREATE TABLE import_jobs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES customers (id),
    source text NOT NULL,
    filename text NULL,
    status text NOT NULL DEFAULT 'queued',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT import_jobs_source_check CHECK (source IN ('csv', 'form')),
    CONSTRAINT import_jobs_status_check CHECK (status IN ('queued', 'done', 'failed'))
);

CREATE TABLE qualification_rules (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES customers (id),
    name text NOT NULL,
    field text NOT NULL,
    pattern text NOT NULL,
    result_status text NOT NULL,
    CONSTRAINT qualification_rules_status_check CHECK (result_status IN ('qualified', 'rejected'))
);

CREATE TABLE outbound_exports (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES customers (id),
    kind text NOT NULL,
    endpoint text NOT NULL,
    status text NOT NULL DEFAULT 'queued',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT outbound_exports_kind_check CHECK (kind IN ('sheets', 'webhook')),
    CONSTRAINT outbound_exports_status_check CHECK (status IN ('queued', 'done', 'failed'))
);
